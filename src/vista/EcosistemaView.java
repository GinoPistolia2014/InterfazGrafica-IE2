    /**
     * Recibe datos simples desde el Controlador y actualiza el JTable.
     */
    public void actualizarTablaEntidades(List<String[]> filas) {
        DefaultTableModel modeloTabla =
                (DefaultTableModel) tblEntidades.getModel();
        modeloTabla.setRowCount(0);

        for (String[] fila : filas) {
            modeloTabla.addRow(fila);
        }
    }

    /**
     * Muestra en la lista los eventos producidos durante el último turno.
     */
    public void actualizarEventos(List<String> eventos) {
        DefaultListModel<String> modeloLista = new DefaultListModel<>();

        if (eventos == null || eventos.isEmpty()) {
            modeloLista.addElement("Aún no se procesó ningún turno.");
        } else {
            for (String evento : eventos) {
                modeloLista.addElement(evento);
            }
        }

        lstEventos.setModel(modeloLista);
    }

